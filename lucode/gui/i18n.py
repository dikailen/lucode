def normalize_language(value: str | None) -> str:
    text = str(value or "").strip().lower()
    if text in SUPPORTED_LANGUAGES:
        return text
    if text.startswith("en"):
        return "en"
    return DEFAULT_LANGUAGE


@dataclass(frozen=True)
class Translator:
    language: str = DEFAULT_LANGUAGE

    def text(self, key: str, **values: Any) -> str:
        language = normalize_language(self.language)
        raw = TRANSLATIONS.get(language, {}).get(key)
        if raw is None:
            raw = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
        return raw.format(**values) if values else raw

    __call__ = text


def tr(key: str, language: str = DEFAULT_LANGUAGE, **values: Any) -> str:
    return Translator(language).text(key, **values)


def load_gui_language(*, workspace_root: Path | str | None = None) -> str:
    config = load_lucode_config(workspace_root=workspace_root)
    ui = config.get("ui") if isinstance(config, dict) else {}
    language = ui.get("language") if isinstance(ui, dict) else None
    return normalize_language(str(language or DEFAULT_LANGUAGE))


def save_gui_language(language: str, *, workspace_root: Path | str | None = None) -> Path:
    normalized = normalize_language(language)
    config = load_lucode_config(workspace_root=workspace_root)
    ui = dict(config.get("ui") or {})
    ui["language"] = normalized
    config["ui"] = ui
    return save_lucode_config(config, workspace_root=workspace_root)
